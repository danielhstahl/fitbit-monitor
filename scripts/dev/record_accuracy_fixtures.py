#!/usr/bin/env python3
"""Record the labelled accuracy fixture the hr-anomaly gate scores itself against.

The fixture is `tests/fixtures/anomaly/hr_anomaly_labels.json`: every labelled episode and
every clean all-night window the accuracy gate asserts on, for a handful of synthetic
wearers generated by the deterministic dev-seed corpus. It is *generated*, never hand-edited,
and it is deliberately small: the heart rate itself is not checked in, because the same seeds
and end date reproduce it byte for byte (see ``tests/test_seed_corpus.py``).

    python scripts/dev/record_accuracy_fixtures.py             # rewrite the fixture
    python scripts/dev/record_accuracy_fixtures.py --check     # fail if it is stale
    python scripts/dev/record_accuracy_fixtures.py --out /tmp/labels.json

Changing the fixture is changing what the detector is required to do, so the diff is the
review: run this, read the diff, and say in the commit message which label moved and why.
The wearers are fixed on purpose - a new seed is a new sample of the generator's noise, and a
floor that moved because a seed was swapped looks identical, in a diff, to a floor that moved
because the detector got worse.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from fitbit_monitor.anomaly.accuracy import (  # noqa: E402
    LabelledCorpus,
    LabelledSuite,
    label_dev_seed,
)
from fitbit_monitor.hr.exercise import DEFAULT_ABSOLUTE_FLOOR_BPM  # noqa: E402
from fitbit_monitor.store.reader import ReadOnlyStore  # noqa: E402
from fitbit_monitor.store.seed import seed_store  # noqa: E402
from fitbit_monitor.store.writer import SeriesStore  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "tests" / "fixtures" / "anomaly" / "hr_anomaly_labels.json"

#: Fixed on purpose - see the module docstring.
END = date(2026, 5, 31)
DAYS = 90
SEEDS: tuple[int, ...] = (1337, 7, 42, 2024, 99)


def build_corpus(seed: int, where: Path) -> LabelledCorpus:
    """Seed one wearer into ``where`` and label it.

    The store is written and re-read through the same two APIs the gate uses, so what the
    fixture says is what the gate will be handed - not what the generator meant to write.
    """
    wearer = f"seed-{seed}"
    path = Path(where) / f"{wearer}.sqlite3"
    writer = SeriesStore(path)
    try:
        plan = seed_store(writer, days=DAYS, seed=seed, end=END)
    finally:
        writer.close()
    reader = ReadOnlyStore(path)
    try:
        return label_dev_seed(wearer, plan, reader, exercise_floor_bpm=DEFAULT_ABSOLUTE_FLOOR_BPM)
    finally:
        reader.close()


def build_suite(where: Path) -> LabelledSuite:
    return LabelledSuite(
        corpora=tuple(build_corpus(seed, where) for seed in SEEDS),
        detail={
            "generator": "fm dev seed (fitbit_monitor.store.seed)",
            "days": DAYS,
            "end": END.isoformat(),
            "seeds": list(SEEDS),
            "exercise_floor_bpm": DEFAULT_ABSOLUTE_FLOOR_BPM,
        },
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="fixture path to write")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if the committed fixture is not what this command would write",
    )
    args = parser.parse_args(argv)
    out = Path(args.out)
    with tempfile.TemporaryDirectory() as tmp:
        suite = build_suite(Path(tmp))
    text = suite.to_json_text()
    episodes = len(suite.episodes)
    windows = len(suite.windows)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"fixture is stale: {out}", file=sys.stderr)
            print(
                f"  recorded {episodes} episode labels and {windows} clean windows would be "
                "written by this command",
                file=sys.stderr,
            )
            print("  run: python scripts/dev/record_accuracy_fixtures.py", file=sys.stderr)
            return 1
        print(f"fixture current: {out} ({episodes} episode labels, {windows} clean windows)")
        return 0
    written = suite.save(out)
    counts: dict[str, int] = {}
    for label in suite.episodes:
        counts[label.verdict] = counts.get(label.verdict, 0) + 1
    verdicts = ", ".join(f"{key}: {value}" for key, value in sorted(counts.items()))
    print(f"wrote {written}")
    print(f"  {len(suite.corpora)} wearers, {episodes} episode labels ({verdicts})")
    print(f"  {windows} clean all-night windows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
